import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import { readFileSync, existsSync, rmSync } from "node:fs";
import { resolve } from "node:path";

const DOCS = resolve(__dirname, "../docs");

// In dev, serve the real site data from docs/data so the app runs against live prices.
const serveSiteData = (): Plugin => ({
  name: "serve-site-data",
  configureServer(server) {
    server.middlewares.use("/data", (req, res, next) => {
      const file = resolve(DOCS, "data", (req.url ?? "").split("?")[0].replace(/^\//, ""));
      if (!file.startsWith(resolve(DOCS, "data")) || !existsSync(file)) return next();
      res.setHeader("Content-Type", "application/json");
      res.end(readFileSync(file));
    });
  },
});

// The build writes into docs/, which also holds docs/data (generated by the Python side and
// committed by the workflows). Never empty docs/; only replace the previous bundle.
const cleanOldBundle = (): Plugin => ({
  name: "clean-old-bundle",
  apply: "build",
  buildStart() {
    rmSync(resolve(DOCS, "assets"), { recursive: true, force: true });
  },
});

export default defineConfig({
  base: "./",
  plugins: [react(), serveSiteData(), cleanOldBundle()],
  build: {
    outDir: DOCS,
    emptyOutDir: false,
    assetsDir: "assets",
    sourcemap: false,
    target: "es2020",
  },
});
